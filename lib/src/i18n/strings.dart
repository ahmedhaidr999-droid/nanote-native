import 'package:flutter/material.dart';

enum Lang { ar, en }

/// Tiny string table with instant AR/EN switching and Arabic-Indic numerals.
///
/// Usage: `Text(S.t('library'))`. Missing keys fall back to English, then to
/// the key itself (never crashes).
class S {
  S._();

  static final ValueNotifier<Lang> lang = ValueNotifier<Lang>(Lang.en);

  /// Optional Hindi (Arabic-Indic ٠١٢٣) digit rendering — OFF by default
  /// (Latin digits always), toggled from Settings (v1.9.1 spec).
  static bool hindiDigits = false;

  static bool get isAr => lang.value == Lang.ar;

  static TextDirection get textDirection =>
      isAr ? TextDirection.rtl : TextDirection.ltr;

  static String t(String key) {
    if (isAr) {
      final a = _ar[key];
      if (a != null) return a;
    }
    return _en[key] ?? key;
  }

  static const List<String> _arDigits = [
    '٠',
    '١',
    '٢',
    '٣',
    '٤',
    '٥',
    '٦',
    '٧',
    '٨',
    '٩',
  ];

  /// Latin digits by default; Hindi (٠١٢٣) only when the setting is on.
  static String num(dynamic n) {
    // dynamic.toString() is statically typed String by the language spec —
    // no cast needed (strict-casts is satisfied).
    final s = n.toString();
    if (!isAr || !hindiDigits) return s;
    return String.fromCharCodes(
      s.runes.map((r) {
        final c = r - 0x30;
        return (c >= 0 && c <= 9) ? _arDigits[c].runes.first : r;
      }),
    );
  }

  static String pageOf(int page, int total) => isAr
      ? '${num(page)} / ${num(total)}'
      : '$page / $total';

